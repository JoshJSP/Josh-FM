// Gedragstest voor mair-sleep.js: verlopen timer, herhaalpogingen en opruimen na de coulance.
import fs from 'node:fs';import vm from 'node:vm';
let fail=0;const ok=(n,c)=>{console.log((c?'PASS ':'FAIL ')+n);if(!c)fail++};
const src=fs.readFileSync(new URL('../mair-sleep.js',import.meta.url),'utf8');
function run(stored,{pauseOk=false}={}){
  const store={jfm_sleep_timer_v1:JSON.stringify(stored)};let pauses=0,now=1e12;const order=[];
  const el=()=>{const p=new Proxy(function(){},{get:(t,k)=>k===Symbol.toPrimitive?()=>'':k==='querySelectorAll'?()=>[]:p,set:()=>true,apply:()=>p});return p};
  let tick;const win={dispatchEvent(){},addEventListener(){},JFMPlayback:{pause:async()=>{pauses++;order.push('pause');return pauseOk},fadeTo:async()=>{order.push('fade');return true},readVolume:async()=>null,volume:1,appliedVolume:1,restoreVolume:async()=>{order.push('restore');return true},health:{}},JFMPlaybackState:{get:()=>({trackId:'t1',expectedLive:true})}};
  const doc={readyState:'complete',getElementById:()=>el(),createElement:el,head:el(),body:{...el(),appendChild(){}},addEventListener(){}};
  const D=class extends Date{static now(){return now}};
  const ctx={window:win,document:doc,localStorage:{getItem:k=>store[k]??null,setItem:(k,v)=>{store[k]=v}},setInterval:(f,ms)=>{if(ms===500)tick=f;return 1},setTimeout(){return 1},clearInterval(){},Date:D,CustomEvent:class{},console,Math,Number,String,JSON};
  ctx.window.localStorage=ctx.localStorage;vm.runInNewContext(src,ctx);
  return {win,order,tick:()=>tick(),pauses:()=>pauses,store,advance:ms=>{now+=ms},now:()=>now};
}
const now0=1e12;const flush=()=>new Promise(r=>setImmediate(r));
const adv=async(r,ms)=>{r.advance(ms);r.tick();await flush();r.tick();await flush()};
let r=run({mode:'time',at:now0-30000,minutes:30,createdAt:now0-1830000});
ok('net verlopen timer blijft bewaard',r.win.MAIRSleep.status().active===true);
r.tick();await flush();
ok('verlopen timer begint met een korte fade, nog geen harde pauze',r.pauses()===0&&r.win.MAIRSleep.status().fading===true);
await adv(r,8200);
ok('verlopen timer pauzeert alsnog na de korte fade',r.pauses()===1);
r.advance(500);r.tick();await flush();
ok('mislukte pauze wordt niet elke 500 ms herhaald',r.pauses()===1);
r.advance(10000);r.tick();await flush();
ok('na 10 s volgt een nieuwe poging',r.pauses()===2);
r.advance(11*60*1000);r.tick();
ok('na de coulance geeft hij het op',r.win.MAIRSleep.status().active===false);
r=run({mode:'time',at:now0-3*3600*1000,minutes:30,createdAt:now0-4*3600*1000});
ok('uren geleden verlopen restant wordt niet meer uitgevoerd',r.win.MAIRSleep.status().active===false);
r=run({mode:'time',at:now0+600000,minutes:10,createdAt:now0});
ok('lopende timer blijft lopen',r.win.MAIRSleep.status().active===true&&r.pauses()===0);
r=run({mode:'time',at:now0-1000,minutes:1,createdAt:now0-61000},{pauseOk:true});r.tick();await flush();await adv(r,8200);
ok('timer: eerst uitfaden, dan pauze, dan volume terug',r.order.join(',')==='fade,pause,restore',r.order.join(','));
r=run({mode:'time',at:now0-1000,minutes:1,createdAt:now0-61000},{pauseOk:false});r.tick();await flush();await adv(r,8200);
ok('ook bij mislukte pauze komt het volume terug',r.order.join(',')==='fade,pause,restore',r.order.join(','));
r.advance(10500);r.tick();await flush();
ok('herhaalpoging na mislukte pauze fadet niet opnieuw',r.order.filter(x=>x==='fade').length===1&&r.order.join(',')==='fade,pause,restore,pause,restore','volgorde '+r.order.join(','));
// Lange fade: begint pas op fadeStart, en eindigt op het stopmoment (klok-gedreven).
r=run({mode:'time',at:now0+600000,minutes:10,createdAt:now0,fadeMs:300000,dj:false});
r.tick();await flush();
ok('lange fade: nog niet begonnen voor het fade-moment',r.order.length===0&&r.win.MAIRSleep.status().fading===false);
await adv(r,320000);
ok('lange fade: op het fade-moment begint hij en zakt het volume',r.win.MAIRSleep.status().fading===true&&r.order.filter(x=>x==='fade').length>=1);
ok('lange fade: nog geen pauze halverwege',r.pauses()===0);
await adv(r,300000);
ok('lange fade: op het stopmoment pauze en volume terug',r.pauses()===1&&r.order.at(-1)==='restore',r.order.slice(-3).join(','));
r=run({mode:'time',at:now0+600000,minutes:10,createdAt:now0,fadeMs:300000});
r.win.MAIRSleep.cancel();await flush();
ok('annuleren zonder lopende fade laat het volume met rust',r.order.length===0&&r.win.MAIRSleep.status().active===false);
r=run({mode:'time',at:now0+600000,minutes:10,createdAt:now0,fadeMs:300000});
await adv(r,320000);r.win.MAIRSleep.cancel();await flush();await flush();
ok('annuleren midden in de fade zet het volume terug en pauzeert niet',r.order.at(-1)==='restore'&&r.pauses()===0&&r.win.MAIRSleep.status().fading===false,r.order.join(','));
console.log(`MAIR sleep timer: ${fail?'FAIL':'PASS'}`);process.exit(fail?1:0);
